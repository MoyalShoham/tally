"""Command line interface.

tally reconcile statement.csv open_items.csv --profile hebrew_debit_credit
tally generate data/generated --seed 7
tally benchmark --seeds 7 11 42 --out benchmarks/results.md
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from tally.evaluation import format_markdown, run_benchmark
from tally.matching.engine import ReconciliationEngine
from tally.models import MatchStatus
from tally.parsing.bank import parse_bank_file
from tally.parsing.ledger import parse_ledger_file
from tally.parsing.profiles import load_profile
from tally.synthetic import bank_csv_hebrew, generate, ledger_csv


def _reconcile(args: argparse.Namespace) -> int:
    bank_path, ledger_path = Path(args.bank), Path(args.ledger)
    parsed = parse_bank_file(bank_path.read_bytes(), bank_path.name, load_profile(args.profile))
    entries = parse_ledger_file(ledger_path.read_bytes(), ledger_path.name)
    resolver = None
    if args.llm:
        from tally.resolver import ClaudeResolver

        resolver = ClaudeResolver()
    report = ReconciliationEngine(resolver=resolver).reconcile(parsed.transactions, entries)

    if args.out:
        Path(args.out).write_text(report.model_dump_json(indent=2), encoding="utf-8")
    s = report.summary
    print(f"{s.transactions} transactions, {s.entries} open entries")
    print(f"  matched automatically: {s.auto_matched_transactions} ({s.auto_match_rate:.0%})")
    print(f"  need review:           {s.review_transactions}")
    print(f"  unmatched:             {s.unmatched_transactions} transactions, {s.unmatched_entries} entries")
    if parsed.skipped_rows:
        print(f"  skipped rows:          {len(parsed.skipped_rows)} (totals, blank lines)")
    if args.show_review:
        txns = {t.id: t for t in parsed.transactions}
        numbers = {e.id: e.number for e in entries}
        print("\nFor review:")
        for match in report.matches:
            if match.status is MatchStatus.REVIEW:
                t = txns[match.transaction_ids[0]]
                docs = ", ".join(numbers[i] for i in match.entry_ids)
                print(
                    f"  {t.date} {t.amount:>12} {t.description[:30]:<30} -> {docs} "
                    f"({match.confidence:.2f}; {match.reasons[0]})"
                )
    return 0


def _generate(args: argparse.Namespace) -> int:
    out = Path(args.directory)
    out.mkdir(parents=True, exist_ok=True)
    dataset = generate(seed=args.seed)
    (out / "statement.csv").write_bytes(bank_csv_hebrew(dataset.transactions))
    (out / "open_items.csv").write_bytes(ledger_csv(dataset.entries))
    print(f"wrote {len(dataset.transactions)} transactions and {len(dataset.entries)} entries to {out}")
    return 0


def _benchmark(args: argparse.Namespace) -> int:
    sections = [
        "# Benchmark results",
        "",
        "Generated by `tally benchmark`. See README for what each scenario means.",
        "",
    ]
    for seed in args.seeds:
        metrics = run_benchmark(seed)
        sections += [f"## Seed {seed}", "", format_markdown(metrics, seed)]
        print(
            f"seed {seed}: auto precision {metrics.auto_precision:.1%}, "
            f"auto recall {metrics.auto_recall:.1%}, found {metrics.found_rate:.1%}"
        )
    if args.out:
        Path(args.out).write_text("\n".join(sections), encoding="utf-8")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="tally", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    sub = parser.add_subparsers(dest="command", required=True)

    rec = sub.add_parser("reconcile", help="match a bank statement to open items")
    rec.add_argument("bank")
    rec.add_argument("ledger")
    rec.add_argument("--profile", default="hebrew_debit_credit")
    rec.add_argument("--out", help="write the full report as JSON")
    rec.add_argument("--show-review", action="store_true", help="list matches that need review")
    rec.add_argument("--llm", action="store_true", help="ask Claude for a second opinion")
    rec.set_defaults(func=_reconcile)

    gen = sub.add_parser("generate", help="write a synthetic statement and ledger")
    gen.add_argument("directory")
    gen.add_argument("--seed", type=int, default=7)
    gen.set_defaults(func=_generate)

    bench = sub.add_parser("benchmark", help="measure precision and recall on synthetic data")
    bench.add_argument("--seeds", type=int, nargs="+", default=[7, 11, 42])
    bench.add_argument("--out")
    bench.set_defaults(func=_benchmark)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    return int(args.func(args))


if __name__ == "__main__":
    sys.exit(main())
